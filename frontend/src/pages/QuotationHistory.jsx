import { useState } from "react";
import { jsPDF } from "jspdf";
import { Download, Printer, Search, FileText, Clock } from "lucide-react";
import { Card, CardContent, CardHeader } from "@/components/ui/Card";
import { Button } from "@/components/ui/Button";
import { Input } from "@/components/ui/Input";
import { Badge } from "@/components/ui/Badge";
import { TableContainer, Table, TableHeader, TableBody, TableRow, TableHead, TableCell } from "@/components/ui/Table";
import { MOCK_QUOTATIONS, STATUS_LABELS, STATUS_BADGE } from "@/data/mockData";
import { formatCurrency, formatDate } from "@/utils/helpers";

function generateQuotationPDF(quote) {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  // Header
  doc.setFillColor(79, 70, 229); // indigo-600
  doc.rect(0, 0, pageWidth, 40, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.setFont("helvetica", "bold");
  doc.text("QuoteForge", 20, 22);
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text("Manufacturing Quotation", 20, 32);
  doc.text("An enterprise-grade industrial quoting platform", 20, 38);

  // Quote meta
  doc.setTextColor(30, 41, 59);
  doc.setFontSize(9);
  doc.text(`Quotation #: ${quote.id}`, 20, 52);
  doc.text(`Date: ${formatDate(quote.createdAt)}`, 20, 60);
  doc.text(`Valid Till: ${formatDate(quote.validTill)}`, 100, 52);

  // Customer info
  doc.setFillColor(241, 245, 249);
  doc.rect(20, 70, pageWidth - 40, 30, "F");
  doc.setTextColor(30, 41, 59);
  doc.setFontSize(10);
  doc.setFont("helvetica", "bold");
  doc.text("Bill To", 25, 80);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.text(quote.customerName, 25, 88);
  doc.text(`Product: ${quote.productName}`, 25, 96);
  doc.text(`Quantity: ${quote.quantity} units`, 100, 88);

  // Items table
  let y = 115;
  doc.setFillColor(79, 70, 229);
  doc.rect(20, y, pageWidth - 40, 8, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(9);
  doc.setFont("helvetica", "bold");
  doc.text("Description", 25, y + 5.5);
  doc.text("Qty", 140, y + 5.5);
  doc.text("Unit Price", 170, y + 5.5);
  doc.text("Amount", pageWidth - 25, y + 5.5, { align: "right" });

  y += 12;
  doc.setTextColor(30, 41, 59);
  doc.setFont("helvetica", "normal");
  doc.rect(20, y, pageWidth - 40, 12);
  doc.text(quote.productName, 25, y + 7);
  doc.text(quote.quantity.toString(), 140, y + 7);
  doc.text(formatCurrency(quote.unitCost), 170, y + 7);
  doc.text(formatCurrency(quote.totalCost), pageWidth - 25, y + 7, { align: "right" });

  // Totals
  y += 20;
  doc.setFont("helvetica", "bold");
  doc.text("Subtotal", pageWidth - 25, y, { align: "right" });
  doc.text(formatCurrency(quote.totalCost), pageWidth - 15, y, { align: "right" });
  doc.text("Total", pageWidth - 25, y + 8, { align: "right" });
  doc.setFontSize(11);
  doc.text(formatCurrency(quote.totalCost), pageWidth - 15, y + 8, { align: "right" });

  // Footer
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.setFont("helvetica", "normal");
  doc.text("Generated by QuoteForge - Professional Manufacturing Quotation", 20, pageHeight - 30);
  doc.text("This is a computer-generated quotation and does not require a signature.", 20, pageHeight - 22);

  doc.save(`${quote.id}.pdf`);
}

export default function QuotationHistory() {
  const [search, setSearch] = useState("");
  const [statusFilter, setStatusFilter] = useState("all");

  const filtered = MOCK_QUOTATIONS.filter((q) => {
    const matchesSearch = q.customerName.toLowerCase().includes(search.toLowerCase()) || q.id.toLowerCase().includes(search.toLowerCase());
    const matchesStatus = statusFilter === "all" || q.status === statusFilter;
    return matchesSearch && matchesStatus;
  });

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-col lg:flex-row lg:items-center lg:justify-between gap-4 page-header">
        <div>
          <h1 className="section-title">Quotation History</h1>
          <p className="section-subtitle">View, print, and generate PDF quotations</p>
        </div>
        <div className="flex items-center gap-2">
          <Button variant="outline" size="small" onClick={() => window.print()}>
            <Printer className="mr-2 size-4" /> Print
          </Button>
          <Button variant="outline" size="small">
            <FileText className="mr-2 size-4" /> New Quotation
          </Button>
        </div>
      </div>

      <Card>
        <CardHeader className="pb-3">
          <div className="flex flex-col lg:flex-row lg:items-center lg:justify-between gap-4">
            <div className="relative w-full lg:w-80">
              <Search className="absolute left-3 top-3 size-5 text-slate-400" />
              <Input
                placeholder="Search quotation # or customer..."
                value={search}
                onChange={(e) => setSearch(e.target.value)}
                className="pl-10"
              />
            </div>
            <div className="flex items-center gap-2">
              <select
                value={statusFilter}
                onChange={(e) => setStatusFilter(e.target.value)}
                className="text-sm border border-slate-200 rounded-md bg-white px-3 py-1.5 focus:outline-none focus:ring-2 focus:ring-indigo-500"
              >
                <option value="all">All statuses</option>
                <option value="draft">Draft</option>
                <option value="sent">Sent</option>
                <option value="approved">Approved</option>
                <option value="rejected">Rejected</option>
              </select>
            </div>
          </div>
        </CardHeader>
        <CardContent>
          <div className="-space-y-px">
            <TableContainer>
              <Table>
                <TableHeader>
                  <TableRow>
                    <TableHead>Quotation #</TableHead>
                    <TableHead>Customer</TableHead>
                    <TableHead className="hidden lg:table-cell">Product</TableHead>
                    <TableHead className="text-right w-20">Qty</TableHead>
                    <TableHead className="text-right w-24">Unit Price</TableHead>
                    <TableHead className="text-right w-24">Total</TableHead>
                    <TableHead className="text-center w-20">Status</TableHead>
                    <TableHead className="text-right w-16">Date</TableHead>
                    <TableHead className="w-28">Actions</TableHead>
                  </TableRow>
                </TableHeader>
                <TableBody>
                  {filtered.length === 0 ? (
                    <TableRow>
                      <TableCell colSpan={9} className="text-center py-8 text-sm text-slate-500">
                        No quotations found
                      </TableCell>
                    </TableRow>
                  ) : (
                    filtered.map((q) => (
                      <TableRow key={q.id}>
                        <TableCell className="font-medium">{q.id}</TableCell>
                        <TableCell className="font-medium">{q.customerName}</TableCell>
                        <TableCell className="hidden lg:table-cell text-sm text-slate-500">{q.productName}</TableCell>
                        <TableCell className="text-right">{q.quantity}</TableCell>
                        <TableCell className="text-right text-sm text-slate-500">{formatCurrency(q.unitCost)}</TableCell>
                        <TableCell className="text-right font-medium">{formatCurrency(q.totalCost)}</TableCell>
                        <TableCell className="text-center">
                          <Badge variant={STATUS_BADGE[q.status]}>{STATUS_LABELS[q.status]}</Badge>
                        </TableCell>
                        <TableCell className="text-right text-xs text-slate-500">{formatDate(q.createdAt)}</TableCell>
                        <TableCell className="text-right">
                          <div className="flex items-center gap-1">
                            <Button size="small" variant="outline" className="p-1.5" title="View Details">
                              <FileText className="size-3.5" />
                            </Button>
                            <Button
                              size="small"
                              variant="ghost"
                              className="p-1.5"
                              title="Download PDF"
                              onClick={() => generateQuotationPDF(q)}
                            >
                              <Download className="size-3.5" />
                            </Button>
                            <Button size="small" variant="ghost" className="p-1.5" title="Print" onClick={() => handlePrint(q)}>
                              <Clock className="size-3.5" />
                            </Button>
                          </div>
                        </TableCell>
                      </TableRow>
                    ))
                  )}
                </TableBody>
              </Table>
            </TableContainer>
          </div>
        </CardContent>
      </Card>
    </div>
  );
}
